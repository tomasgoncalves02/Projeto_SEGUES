/**
 * Order Reporting and Management UI Controller.
 * Handles detailed order retrieval, dynamic table updates, and administrative 
 * toggle synchronization for weekend operations.
 */
import { DOM, Notifications, Api } from "../core/core.js";

/**
 * Fetches and displays detailed information about a specific order in a modal.
 * @param {number|string} id - The unique identifier of the order.
 * @remarks
 * Implements a "Loading State" pattern: 
 * 1. Shows a spinner while fetching data.
 * 2. Handles API error/not-found states with specific visual feedback.
 * 3. Renders a responsive HTML table with product breakdown and redemption codes.
 */
async function showOrderDetails(id) {
    // UI Feedback: Create a modal with loading spinner while the request is pending
    Notifications.loading();

    // Data Acquisition
    const data = await Api.get(`/Report/ReportOrder/GetOrderDetails/${id}`);

    if (!data) return;

    // Error Handling: API returns a 400 or specific error message
    if (data.errorMessage) {
        Notifications.loadingError(`<div class="p-4 text-danger text-center">${data.errorMessage}</div>`);
        return;
    }

    // Edge Case: Order not found or empty
    if (data.failMessage) {
        Notifications.loadingSuccessEmpty(`<div class="p-4 text-center text-muted">${data.failMessage}</div>`);
        return;
    }

    // Template Generation: Maps product objects into HTML table rows
    const rows = data.products.map(p => `
        <tr class="align-middle">
            <td class="text-start">
                <div class="fw-bold">${p.name}</div>
                <div class="small text-muted" title="${p.categoryDescription}">${p.categoryName}</div>
            </td>
            <td class="fw-bold">${p.quantity}</td>
            <td class="text-color-ips fw-bold">${p.price}</td>
        </tr>
        `).join('');

    // Success View: Transition from spinner to content modal
    Notifications.loadingSuccess(
        'Detalhes do Pedido', `
        <div class="my-2">
            <p class="mb-2 text-muted fw-bold small fs-md-5">Código de Recolha</p>
            <h4 class="text-color-ips fw-bold bg-color-ips-light d-inline-block px-3 py-2 rounded border" style="letter-spacing: 2px;">${data.code}</h4>
        </div>
        <div class="table-responsive border rounded-3 shadow-sm">
            <table class="table table-hover mb-0">
                <thead class="bg-color-ips text-white">
                    <tr>
                        <th class="text-start ps-3">Produto</th>
                        <th>Qtd</th>
                        <th>Preço</th>
                    </tr>
                </thead>
                <tbody class="text-center">${rows}</tbody>
            </table>
        </div>
    `);
}

/**
 * Updates the UI badge indicating the total number of orders listed.
 */
function updateOrdersCount() {
    const rowCount = DOM.byClass('showOrderDetails')?.length || 0;
    const badge = DOM.byId('ordersCountBadge');
    if (!badge) return;

    badge.textContent = rowCount.toString(10);
}

/**
 * Synchronizes client-side filters with the hidden export form.
 * @param {Event} e - Form submission event.
 * @remarks
 * Ensures that the PDF generated by the server matches the filters 
 * currently visible to the user on the screen.
 */
function syncExportData(e) {
    e.preventDefault();
    const form = DOM.byId('exportPdfForm');
    if (!form) return;

    // Manual sync: Fetch values from the visible filter UI
    DOM.byId('exportPdfSearch').value = DOM.byId('searchFilter')?.value || '';
    DOM.byId('exportPdfDate').value = DOM.byId('dateFilter')?.value || '';
    DOM.byId('exportPdfStatus').value = DOM.byId('statusFilter')?.value || '';

    form.submit();
}

/**
 * ReportOrder Module initialization and event handling.
 */
const ReportOrder = {
    init() {
        DOM.delegate('showOrderDetails', 'click', async function () {
            await showOrderDetails(this.dataset.id);
        });
        DOM.bind('exportPdfForm', 'submit', syncExportData);
        DOM.bind('switchSat', 'change', function () {
            DOM.byId('formSat').submit();
        });
        DOM.bind('switchSun', 'change', function () {
            DOM.byId('formSun').submit();
        });
    }
};

// Application Lifecycle
DOM.bindDocumentLoad(ReportOrder.init);
DOM.executeAfterHtmx(updateOrdersCount);

export { ReportOrder };